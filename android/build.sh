#!/usr/bin/env bash
# Builds the DCC Portal Android app (APK) without Gradle, using the command-line
# Android build tools: aapt2, javac, dx (dalvik-exchange), zipalign, apksigner.
#
#   ./build.sh debug                         # debug APK (HTTP allowed for private LAN addresses)
#   ./build.sh release                       # signed release APK (HTTPS only); needs the env vars below
#
# Optional environment variables:
#   PORTAL_URL         Built-in portal address, e.g. https://portal.example.edu.in
#                      (if empty, the app asks for the address on first launch)
#   VERSION_CODE       Integer, increase for every release (default 1)
#   VERSION_NAME       e.g. 1.0.0 (default 1.0.0)
#   ANDROID_JAR        Path to an API 35 android.jar (downloaded and cached if not set)
#   ANDROID_HOME       Android SDK; platforms/android-35/android.jar is used if present
#   Release signing:   DCC_KEYSTORE, DCC_KEYSTORE_PASS, DCC_KEY_ALIAS, DCC_KEY_PASS
set -euo pipefail

VARIANT="${1:-debug}"
case "$VARIANT" in debug|release) ;; *) echo "usage: $0 [debug|release]" >&2; exit 2 ;; esac

ROOT="$(cd "$(dirname "$0")" && pwd)"
APP="$ROOT/app/src"
OUT="$ROOT/build/$VARIANT"
CACHE="$ROOT/.cache"
APPLICATION_ID="com.damdeichristiancollege.portal"
MIN_SDK=26
TARGET_SDK=35
VERSION_CODE="${VERSION_CODE:-1}"
VERSION_NAME="${VERSION_NAME:-1.0.0}"
PORTAL_URL="${PORTAL_URL:-}"

for tool in aapt2 javac dalvik-exchange zipalign apksigner keytool unzip zip; do
  command -v "$tool" >/dev/null || { echo "Missing tool: $tool (see android/README.md)" >&2; exit 1; }
done

# --- Android framework jars ---------------------------------------------------------
# Java is compiled against API 35. Any API 35 android.jar works (for example
# $ANDROID_HOME/platforms/android-35/android.jar). Without one, the Robolectric
# "android-all" framework jar is fetched from the Gradle plugin portal's Maven mirror
# and its SHA-1 checked. Resources are linked against a framework resource table
# that the installed aapt2 can read: the same jar if possible, otherwise Android 14's
# (framework resource IDs are stable across versions).
fetch_android_all() { # $1 = version, prints the cached path
  local v="$1" dest="$CACHE/android-all-$1.jar"
  if [[ ! -f "$dest" ]]; then
    mkdir -p "$CACHE"
    local url="https://plugins.gradle.org/m2/org/robolectric/android-all/$v/android-all-$v.jar"
    echo "Downloading framework jar $v…" >&2
    curl -sSfL -o "$dest.tmp" "$url"
    local expected actual
    expected="$(curl -sSfL "$url.sha1" | cut -c1-40)"
    actual="$(sha1sum "$dest.tmp" | cut -c1-40)"
    [[ "$expected" == "$actual" ]] || { echo "Checksum mismatch for $url" >&2; rm -f "$dest.tmp"; exit 1; }
    mv "$dest.tmp" "$dest"
  fi
  printf '%s' "$dest"
}

if [[ -z "${ANDROID_JAR:-}" ]]; then
  if [[ -n "${ANDROID_HOME:-}" && -f "$ANDROID_HOME/platforms/android-$TARGET_SDK/android.jar" ]]; then
    ANDROID_JAR="$ANDROID_HOME/platforms/android-$TARGET_SDK/android.jar"
  else
    ANDROID_JAR="$(fetch_android_all 15-robolectric-13954326)"
  fi
fi
if aapt2 dump resources "$ANDROID_JAR" 2>/dev/null | grep -q 'attr/dataExtractionRules'; then
  RES_JAR="$ANDROID_JAR"
else
  RES_JAR="$(fetch_android_all 14-robolectric-10818077)"
fi

# --- Validate the built-in portal address ------------------------------------------
if [[ -n "$PORTAL_URL" ]]; then
  if [[ "$VARIANT" == release && "$PORTAL_URL" != https://* ]]; then
    echo "PORTAL_URL must use https:// for release builds" >&2; exit 1
  fi
fi

rm -rf "$OUT"
mkdir -p "$OUT"/{gen,res,classes,apk}

# --- Generated BuildConfig ---------------------------------------------------------
DEBUG_FLAG=false; [[ "$VARIANT" == debug ]] && DEBUG_FLAG=true
esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
mkdir -p "$OUT/gen/com/damdeichristiancollege/portal"
cat > "$OUT/gen/com/damdeichristiancollege/portal/BuildConfig.java" <<JAVA
package com.damdeichristiancollege.portal;

/** Generated by build.sh. Do not edit. */
public final class BuildConfig {
    public static final boolean DEBUG = $DEBUG_FLAG;
    public static final String APPLICATION_ID = "$APPLICATION_ID";
    public static final String VERSION_NAME = "$(esc "$VERSION_NAME")";
    public static final int VERSION_CODE = $VERSION_CODE;
    public static final String DEFAULT_PORTAL_URL = "$(esc "$PORTAL_URL")";
    private BuildConfig() {}
}
JAVA

# --- Resources ----------------------------------------------------------------------
echo "Compiling resources…"
aapt2 compile --dir "$APP/main/res" -o "$OUT/res/main.zip"
OVERLAY=()
if [[ -d "$APP/$VARIANT/res" ]]; then
  aapt2 compile --dir "$APP/$VARIANT/res" -o "$OUT/res/$VARIANT.zip"
  OVERLAY=(-R "$OUT/res/$VARIANT.zip")
fi
LINK_FLAGS=()
[[ "$VARIANT" == debug ]] && LINK_FLAGS+=(--debug-mode)
aapt2 link -o "$OUT/apk/resources.apk" \
  -I "$RES_JAR" \
  --manifest "$APP/main/AndroidManifest.xml" \
  --rename-manifest-package "$APPLICATION_ID" \
  --min-sdk-version "$MIN_SDK" --target-sdk-version "$TARGET_SDK" \
  --version-code "$VERSION_CODE" --version-name "$VERSION_NAME" \
  --java "$OUT/gen" --auto-add-overlay \
  "${LINK_FLAGS[@]}" \
  "$OUT/res/main.zip" "${OVERLAY[@]}"

# --- Java -> class files -> dex ------------------------------------------------------
echo "Compiling Java…"
find "$APP/main/java" "$OUT/gen" -name '*.java' > "$OUT/sources.txt"
javac --release 8 -nowarn -Xlint:-options -encoding UTF-8 \
  -classpath "$ANDROID_JAR" -d "$OUT/classes" @"$OUT/sources.txt"

echo "Dexing…"
dalvik-exchange --dex --min-sdk-version="$MIN_SDK" --output="$OUT/apk/classes.dex" "$OUT/classes"

# --- Package, align, sign -------------------------------------------------------------
cp "$OUT/apk/resources.apk" "$OUT/apk/unsigned.apk"
(cd "$OUT/apk" && zip -q -j unsigned.apk classes.dex)
zipalign -f -p 4 "$OUT/apk/unsigned.apk" "$OUT/apk/aligned.apk"

if [[ "$VARIANT" == debug ]]; then
  KS="$CACHE/debug.keystore"
  if [[ ! -f "$KS" ]]; then
    mkdir -p "$CACHE"
    keytool -genkeypair -keystore "$KS" -storepass android -keypass android -alias androiddebugkey \
      -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Android Debug,O=Android,C=US" >/dev/null 2>&1
  fi
  SIGN=(--ks "$KS" --ks-pass pass:android --ks-key-alias androiddebugkey --key-pass pass:android)
else
  : "${DCC_KEYSTORE:?Set DCC_KEYSTORE (see android/README.md › Release signing)}"
  : "${DCC_KEYSTORE_PASS:?Set DCC_KEYSTORE_PASS}"
  : "${DCC_KEY_ALIAS:?Set DCC_KEY_ALIAS}"
  SIGN=(--ks "$DCC_KEYSTORE" --ks-pass env:DCC_KEYSTORE_PASS --ks-key-alias "$DCC_KEY_ALIAS" --key-pass "env:${DCC_KEY_PASS:+DCC_KEY_PASS}")
  [[ -z "${DCC_KEY_PASS:-}" ]] && SIGN=(--ks "$DCC_KEYSTORE" --ks-pass env:DCC_KEYSTORE_PASS --ks-key-alias "$DCC_KEY_ALIAS")
fi

FINAL="$ROOT/build/dcc-portal-$VERSION_NAME-$VARIANT.apk"
apksigner sign "${SIGN[@]}" --min-sdk-version "$MIN_SDK" --out "$FINAL" "$OUT/apk/aligned.apk"
apksigner verify --min-sdk-version "$MIN_SDK" "$FINAL"
rm -f "$FINAL.idsig"
echo "Built $FINAL ($(du -h "$FINAL" | cut -f1))"
