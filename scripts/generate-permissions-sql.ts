/**
 * Generates the roles/permissions reference-data migration from
 * src/lib/auth/permissions.ts. Run: pnpm db:gen-permissions
 *
 * The generated migration is idempotent (upserts) and also re-syncs default
 * role grants for system roles.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PERMISSIONS, ROLES, ROLE_PERMISSIONS } from "../src/lib/auth/permissions";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const lines: string[] = [];
lines.push("-- =============================================================================");
lines.push("-- GENERATED by scripts/generate-permissions-sql.ts — do not edit by hand.");
lines.push("-- Source of truth: src/lib/auth/permissions.ts");
lines.push("-- =============================================================================");
lines.push("");
lines.push("insert into public.roles (key, name, description, is_system) values");
lines.push(
  Object.entries(ROLES)
    .map(([k, r]) => `  (${q(k)}, ${q(r.name)}, ${q(r.description)}, true)`)
    .join(",\n") +
    "\non conflict (key) do update set name = excluded.name, description = excluded.description;",
);
lines.push("");
lines.push("insert into public.permissions (key, module, description) values");
lines.push(
  Object.entries(PERMISSIONS)
    .map(([k, p]) => `  (${q(k)}, ${q(p.module)}, ${q(p.description)})`)
    .join(",\n") +
    "\non conflict (key) do update set module = excluded.module, description = excluded.description;",
);
lines.push("");
lines.push("delete from public.role_permissions rp using public.roles r");
lines.push("  where rp.role_id = r.id and r.is_system;");
lines.push("");
lines.push("insert into public.role_permissions (role_id, permission_key)");
lines.push("select r.id, v.permission_key from (values");
const pairs: string[] = [];
for (const [role, perms] of Object.entries(ROLE_PERMISSIONS)) {
  for (const p of perms) pairs.push(`  (${q(role)}, ${q(p)})`);
}
lines.push(pairs.join(",\n"));
lines.push(") as v(role_key, permission_key)");
lines.push("join public.roles r on r.key = v.role_key;");
lines.push("");

const out = join(__dirname, "..", "supabase", "migrations", "20261029000008_roles_permissions.sql");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out} (${pairs.length} grants)`);

// Human-readable matrix for docs/PERMISSIONS_MATRIX.md
const roles = Object.keys(ROLES) as (keyof typeof ROLES)[];
const md: string[] = [
  "# User role and permissions matrix",
  "",
  "> Generated from `src/lib/auth/permissions.ts` by `pnpm db:gen-permissions`. Do not edit by hand.",
  "",
  "## Roles",
  "",
  "| Role | Description |",
  "|---|---|",
  ...roles.map((r) => `| **${ROLES[r].name}** (\`${r}\`) | ${ROLES[r].description} |`),
  "",
  "## Permissions",
  "",
  "✅ = granted. Ownership rules apply on top of these permissions (enforced by Row Level Security):",
  "",
  "- **Teachers** see only students, attendance and marks for course offerings they are assigned to (as teacher or examiner).",
  "- **Students** see only their own profile, attendance, fees and receipts, and their own results *after publication*.",
  "- **Notices** are visible only when published, within their publish/expiry window, and targeted at the reader.",
  "",
  `| Permission | Description | ${roles.map((r) => ROLES[r].name).join(" | ")} |`,
  `|---|---|${roles.map(() => ":-:").join("|")}|`,
];
let lastModule = "";
for (const [k, p] of Object.entries(PERMISSIONS)) {
  if (p.module !== lastModule) {
    md.push(`| **${p.module}** | | ${roles.map(() => "").join(" | ")} |`);
    lastModule = p.module;
  }
  md.push(`| \`${k}\` | ${p.description} | ${roles.map((r) => ((ROLE_PERMISSIONS[r] as readonly string[]).includes(k) ? "✅" : "")).join(" | ")} |`);
}
md.push("", "## Separation of duties", "",
  "- Results: the Examination Controller **processes** and **publishes**; the Principal **approves**. Neither can do the other's step. Only a Super Administrator can **withdraw** published results (reason required, audited).",
  "- Concessions/waivers: requested by the Accountant, approved by someone else (Principal); the database rejects self-approval.",
  "- Payments are immutable; corrections are reversals with a mandatory reason.",
  "- Role grants go through an audited database function; nobody can elevate their own role, and only a Super Administrator can grant Super Administrator.",
  "");
mkdirSync(join(__dirname, "..", "docs"), { recursive: true });
const docOut = join(__dirname, "..", "docs", "PERMISSIONS_MATRIX.md");
writeFileSync(docOut, md.join("\n"));
console.log(`Wrote ${docOut}`);
